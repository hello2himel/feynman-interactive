    for (var n = btn.firstChild; n; n = n.nextSibling) {
      if (n.nodeType === 3 && n.nodeValue.trim() !== "") {
        t = n;
        break;
      }
    }
    if (!t) return;
    var s = document.createElement("span");
    s.className = "btn-label";
    s.textContent = t.nodeValue.trim();
    btn.replaceChild(s, t);
