/* Mirror theme control: light / dark / system.
 *
 * Loaded synchronously in <head> (see scripts/theme_patch.py) so the stored
 * choice applies before first paint (no theme flash). The toggle button
 * itself is wired on DOMContentLoaded.
 *
 * Modes: null = follow the OS (default, attribute removed), or explicit
 * "light" / "dark" pinned via the data-theme attribute and localStorage.
 */
(function () {
  var KEY = "feynman-theme";
  var MODES = {
    system: {
      icon: "contrast-2",
      word: "System",
      title: "Colour theme: follows your system. Activate to pin Light.",
      aria: "Colour theme: System, following your system. Activate to pin Light."
    },
    light: {
      icon: "sun",
      word: "Light",
      title: "Colour theme: pinned to Light. Activate to pin Dark.",
      aria: "Colour theme: Light. Activate to pin Dark."
    },
    dark: {
      icon: "moon",
      word: "Dark",
      title: "Colour theme: pinned to Dark. Activate to follow your system.",
      aria: "Colour theme: Dark. Activate to follow your system."
    }
  };

  function stored() {
    try {
      return window.localStorage.getItem(KEY);
    } catch (e) {
      return null;
    }
  }

  function save(mode) {
    try {
      if (mode === null) window.localStorage.removeItem(KEY);
      else window.localStorage.setItem(KEY, mode);
    } catch (e) {
      /* storage unavailable: still apply for this session */
    }
  }

  function current() {
    var s = stored();
    return s === "light" || s === "dark" ? s : null;
  }

  function paint(mode) {
    var el = document.documentElement;
    var key = mode === "light" || mode === "dark" ? mode : "system";
    if (key === "system") el.removeAttribute("data-theme");
    else el.setAttribute("data-theme", key);
    var btn = document.getElementById("theme");
    if (btn) {
      var m = MODES[key];
      btn.innerHTML = "";
      btn.appendChild(riIcon(m.icon));
      btn.appendChild(document.createTextNode(" " + m.word));
      btn.setAttribute("title", m.title);
      btn.setAttribute("aria-label", m.aria);
    }
  }

  function cycle() {
    var cur = current();
    var next = cur === null ? "light" : cur === "light" ? "dark" : null;
    save(next);
    paint(next);
  }

  window.__feynmanThemeCycle = cycle;

  paint(current());

  document.addEventListener("DOMContentLoaded", function () {
    paint(current());
    var btn = document.getElementById("theme");
    if (btn && !btn.dataset.wired) {
      btn.dataset.wired = "1";
      btn.addEventListener("click", cycle);
    }
  });
})();

